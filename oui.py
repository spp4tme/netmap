def lookup(mac_bytes: bytes) -> str:
    """Return manufacturer for the given MAC bytes, or empty string if unknown."""
    if len(mac_bytes) < 3:
        return ""
    key = ":".join(f"{b:02X}" for b in mac_bytes[:3])
    return _OUI.get(key, "")


